export const getCommunesByWilaya = (wilaya) =>
  COMMUNES.filter(c => c.wilaya === wilaya);

export const searchCommunes = (query) => {
  if (!query || query.length < 2) return [];
  const normalize = (str) => str.toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/'/g, " ");
  const q = normalize(query);
  const startsWith = COMMUNES.filter(c =>
    normalize(c.commune).startsWith(q) || normalize(c.wilaya).startsWith(q)
  );
  const contains = COMMUNES.filter(c =>
    !normalize(c.commune).startsWith(q) &&
    !normalize(c.wilaya).startsWith(q) &&
    (normalize(c.commune).includes(q) || normalize(c.wilaya).includes(q))
  );
  return [...startsWith, ...contains].slice(0, 10);
};
